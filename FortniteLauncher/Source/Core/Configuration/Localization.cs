        public static void SetLanguage(string LanguageTag)
        {
            CurrentLanguage = Strings.ContainsKey(LanguageTag) ? LanguageTag : "en-US";
            LanguageChanged?.Invoke();
        }

        public static string Get(string Key)
        {
            if (Strings.TryGetValue(CurrentLanguage, out var dict) && dict.TryGetValue(Key, out var value))
                return value;

            return Strings["en-US"].TryGetValue(Key, out var fallback) ? fallback : Key;
        }
